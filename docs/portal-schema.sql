-- Helper: resolve business_id for the calling auth user
CREATE OR REPLACE FUNCTION my_business_id()
RETURNS uuid AS $$
  SELECT business_id FROM portal_accounts WHERE auth_user_id = auth.uid() LIMIT 1;
$$ LANGUAGE sql STABLE SECURITY DEFINER;

-- businesses: owner/staff read their own business
CREATE POLICY "business_read_own" ON businesses
  FOR SELECT USING (id = my_business_id());

-- portal_accounts: user reads their own row
CREATE POLICY "account_read_own" ON portal_accounts
  FOR SELECT USING (auth_user_id = auth.uid());

-- billing_schedule: read own business bills
CREATE POLICY "billing_read_own" ON billing_schedule
  FOR SELECT USING (business_id = my_business_id());

-- billing_notifications: read own business notifications
CREATE POLICY "notif_read_own" ON billing_notifications
  FOR SELECT USING (business_id = my_business_id());

-- portal_messages: read general messages or own-business messages
CREATE POLICY "messages_read_own" ON portal_messages
  FOR SELECT USING (business_id IS NULL OR business_id = my_business_id());

